/*
 * OPERATION MOONLIGHT — библиотека Season 5: разбор CSV
 * Извлечено из s05e03.
 *
 * Потоковый разбор конечным автоматом: файл читается по байту, в памяти
 * живёт одна запись. Потребление памяти не зависит от размера файла.
 *
 * Поддерживается: поля в кавычках, удвоенная кавычка внутри поля,
 * разделитель и перевод строки внутри поля, CRLF и LF вперемешку.
 *
 * Используется в s08e02 (чтение данных вместо генерации) и s10e07.
 */
#ifndef ML_CSV_H
#define ML_CSV_H

#include <stdio.h>
#include <stddef.h>

#define ML_CSV_MAX_FIELDS  32
#define ML_CSV_ROW_BYTES 4096

/* Причина, по которой запись признана негодной. */
enum {
    ML_CSV_OK       = 0,
    ML_CSV_OVERFLOW = 1,      /* запись не поместилась в буфер   */
    ML_CSV_UNTERMINATED = 2   /* кавычка не закрыта к концу файла */
};

typedef struct {
    char   buf[ML_CSV_ROW_BYTES];
    char  *field[ML_CSV_MAX_FIELDS];
    int    nfield;
    int    status;            /* ML_CSV_OK или причина порчи      */
    long   offset;            /* смещение начала записи в файле   */
} ml_csv_row;

/* Обработчик записи. Возврат 0 останавливает разбор, ненулевой — продолжает.
   Запись действительна только на время вызова: буфер переиспользуется. */
typedef int (*ml_csv_cb)(const ml_csv_row *row, void *user);

/* Разобрать поток целиком, вызывая cb на каждой записи (включая порченые:
   их видно по row->status). Файл должен быть открыт в двоичном режиме,
   иначе автомат не увидит \r.

   Возвращает число записей, переданных в cb; при незакрытой кавычке
   последняя запись придёт со статусом ML_CSV_UNTERMINATED. */
long ml_csv_parse(FILE *f, char delim, ml_csv_cb cb, void *user);

/* Разобрать одну строку в памяти (без переводов строки внутри полей).
   Строка портится: разделители заменяются нулями. Возвращает число полей. */
int ml_csv_split_line(char *line, char delim, char **field, int maxfield);

#endif /* ML_CSV_H */
