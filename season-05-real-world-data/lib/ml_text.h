/*
 * OPERATION MOONLIGHT — библиотека Season 5: текст в UTF-8
 * Извлечено из s05e08.
 *
 * У строки три длины: байты, кодовые точки и знакоместа. Ни одна не
 * выводится из другой, и путать их дорого — в частности, "%-16s"
 * считает байты и потому разъезжает на любом не-ASCII тексте.
 *
 * Используется в s09e06 и s10e06: с этим модулем оговорка
 * «в выровненных колонках только ASCII» из курса снимается.
 */
#ifndef ML_TEXT_H
#define ML_TEXT_H

#include <stdint.h>
#include <stddef.h>

/* Разобрать одну кодовую точку. Возвращает число съеденных байт или 0,
   если последовательность недопустима. Переусложнённая запись и точки
   выше U+10FFFF считаются ошибкой, а не вариантом записи: иначе любая
   проверка, работающая с байтами, обходится. */
int ml_utf8_decode(const char *s, uint32_t *cp);

/* Число кодовых точек. Не байт и не знакомест. */
size_t ml_len_points(const char *s);

/* Ширина кодовой точки в знакоместах: 0 — комбинирующие знаки,
   2 — иероглифы и знаки полной ширины, 1 — остальное.
   Таблица сокращённая; точной ширины в общем случае не существует. */
int ml_cp_width(uint32_t cp);

/* Ширина строки в знакоместах. */
size_t ml_len_columns(const char *s);

/* Печать с добивкой пробелами до width ЗНАКОМЕСТ. */
void ml_pad_cols(const char *s, size_t width);

/* ---- алфавиты ---- */

enum { ML_SC_OTHER = 0, ML_SC_LATIN = 1, ML_SC_CYRILLIC = 2, ML_SC_HAN = 4 };

int ml_cp_script(uint32_t cp);

/* Набор алфавитов, встретившихся в строке (маска ML_SC_*). */
int ml_scripts_of(const char *s);

/* Подозрительное сочетание письменностей в одной строке. */
int ml_suspicious_scripts(const char *s);

/* ---- двойники ---- */

/* Кириллическая буква, неотличимая от латинской, -> латинская.
   Часть таблицы confusables из UTS #39. */
uint32_t ml_deconfuse(uint32_t cp);

/* Скелет: вид, в котором сравнение отвечает на вопрос «выглядят ли
   они одинаково», а не «равны ли они». Двойники сведены, комбинирующие
   знаки отброшены, регистр приведён к нижнему. */
void ml_skeleton(const char *s, char *out, size_t n);

/* Совпадают ли скелеты двух строк. */
int ml_looks_same(const char *a, const char *b);

#endif /* ML_TEXT_H */
