/*
 * OPERATION MOONLIGHT — библиотека Season 5: деньги в фиксированной точке
 * Извлечено из s05e02.
 *
 * Деньги хранятся целыми в минимальных единицах (для доллара — в центах).
 * Ни одна операция модуля не использует double: суммы обязаны сходиться
 * при сверке, а сверка не терпит погрешности представления.
 *
 * Используется в s05e05 (комиссии в бэктесте) и s10e07 (сведение баланса).
 */
#ifndef ML_MONEY_H
#define ML_MONEY_H

#include <stdint.h>
#include <stddef.h>

typedef int64_t ml_money_t;          /* минимальные единицы */

/* Режимы округления при умножении на долю. */
enum {
    ML_ROUND_TRUNC     = 0,          /* отбросить дробную часть (к нулю)  */
    ML_ROUND_HALF_UP   = 1,          /* ровно половина — от нуля          */
    ML_ROUND_HALF_EVEN = 2           /* ровно половина — к чётному        */
};

/* Разбор "1234.56" в минимальные единицы при scale = 100.
   scale — число минимальных единиц в целой: 100 для центов, 10000 для
   десятитысячных. Возвращает 1 при успехе, 0 при неверном формате.
   Отвергает: лишние знаки после точки, точку без цифр, любой мусор. */
int ml_money_parse(const char *s, int scale, ml_money_t *out);

/* Печать в buf в виде "1234.56". Знак выносится перед целой частью,
   поэтому -4 при scale = 100 даёт "-0.04", а не "0.-4".
   Возвращает 1 при успехе, 0 если буфера не хватило. */
int ml_money_str(ml_money_t m, int scale, char *buf, size_t n);

/* Умножение на долю, заданную в миллионных (ppm): 0.15% = 1500.
   Округление по mode. Шаг всегда от нуля, поэтому плюсы и минусы
   ведут себя симметрично и не маскируют систематический сдвиг.
   Внимание: amount * ppm должно умещаться в int64_t. */
ml_money_t ml_money_mul_ppm(ml_money_t amount, int64_t ppm, int mode);

/* Сложение с обнаружением переполнения. При переполнении возвращает 0
   и не трогает *out; иначе возвращает 1. */
int ml_money_add(ml_money_t a, ml_money_t b, ml_money_t *out);

/* Деление суммы на n равных долей без потери единиц: первые
   (amount mod n) долей получают на единицу больше остальных.
   Сумма всех долей ровно равна amount — это и есть смысл функции.
   Возвращает 1 при успехе, 0 при n <= 0. */
int ml_money_split(ml_money_t amount, int n, ml_money_t *parts);

#endif /* ML_MONEY_H */
