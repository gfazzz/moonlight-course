/*
 * OPERATION MOONLIGHT — s09e07 "Радар и фильтр Калмана"
 * Эталонное решение: kalman.c
 *
 * Концепт серии: датчик врёт. Показывать сырое измерение нельзя — отметка цели
 *                будет прыгать. Но и слепо верить модели движения нельзя — цель
 *                маневрирует. Фильтр Калмана объединяет оба источника, ВЗВЕШИВАЯ
 *                их по неопределённости:
 *                  предсказание (модель) -> коррекция (измерение)
 *                Вес измерения — коэффициент усиления K. Он растёт, когда модель
 *                неуверена, и падает, когда шумит датчик. Причём фильтр сам
 *                отслеживает свою неопределённость P — это и делает его «умным».
 * Задача: одномерное сопровождение цели (положение + скорость) по шумному радару.
 *
 * Реализация: состояние [x, v], модель постоянной скорости, ковариация 2x2
 * записана поэлементно (p00, p01, p10, p11) — без библиотеки матриц, но это
 * полноценный фильтр, а не упрощение. Скалярной P здесь недостаточно: именно
 * ВНЕДИАГОНАЛЬНЫЕ элементы связывают положение со скоростью и позволяют
 * выучить скорость, измеряя только координату.
 * Все вычисления детерминированы, шум — из собственного ГПСЧ.
 */
#include <stdio.h>

#define STEPS 30
#define DT    1.0        /* шаг времени, с */

/* Свой sqrt (Ньютон) — без -lm, как в предыдущих сезонах. */
static double my_sqrt(double x) {
    if (x <= 0.0) return 0.0;
    double g = x;
    for (int i = 0; i < 40; i++) g = 0.5 * (g + x / g);
    return g;
}

/* Детерминированный гауссов шум: сумма 12 равномерных минус 6 (ЦПТ, как в S5/S8). */
static unsigned long rs = 424242UL;
static double uniform(void) {
    rs = rs * 1103515245UL + 12345UL;
    return (double)((rs >> 16) & 0x7FFF) / 32768.0;
}
static double gauss(double sigma) {
    double acc = 0.0;
    for (int i = 0; i < 12; i++) acc += uniform();
    return (acc - 6.0) * sigma;
}

int main(void) {
    /* Истина: цель летит с постоянной скоростью 12 м/с из точки 100 м. */
    double true_x = 100.0, true_v = 12.0;

    /* Шумы: измерения (R) и процесса (Q). Их отношение и определяет поведение фильтра. */
    const double R = 25.0;      /* дисперсия шума радара: sigma = 5 м */
    const double Q = 0.05;      /* дисперсия шума модели: цель почти не маневрирует */

    /* Состояние фильтра: [x, v] и матрица ковариации P (2x2).
       Скалярной P здесь недостаточно: положение и скорость СВЯЗАНЫ, и именно
       внедиагональные элементы позволяют фильтру выучить скорость по положению. */
    double x = 0.0, v = 0.0;
    double p00 = 500.0, p01 = 0.0, p10 = 0.0, p11 = 500.0;   /* полная неуверенность */

    printf("=== фильтр Калмана: сопровождение цели ===\n");
    printf("истина: старт %.0f м, скорость %.0f м/с; шум радара sigma=%.0f м\n",
           true_x, true_v, my_sqrt(R));
    printf("старт фильтра: x=%.0f v=%.0f, P=%.0f (полная неопределённость)\n\n", x, v, p00);

    printf("шаг  истина  измерение   оценка   скорость     K0     |изм-ист|  |оцен-ист|\n");
    printf("--------------------------------------------------------------------------\n");

    double sum_meas_err = 0.0, sum_est_err = 0.0;

    for (int k = 1; k <= STEPS; k++) {
        /* --- реальный мир --- */
        true_x += true_v * DT;
        double z = true_x + gauss(my_sqrt(R));      /* радар выдал зашумлённое измерение */

        /* --- 1. Предсказание: x = F x, P = F P F^T + Q --- */
        x = x + v * DT;
        /* F = [[1, dt], [0, 1]] -> раскрытое умножение F P F^T */
        double n00 = p00 + DT * (p10 + p01) + DT * DT * p11;
        double n01 = p01 + DT * p11;
        double n10 = p10 + DT * p11;
        double n11 = p11;
        p00 = n00 + Q;                              /* шум процесса */
        p01 = n01;
        p10 = n10;
        p11 = n11 + Q;

        /* --- 2. Коррекция: измеряем только положение, H = [1 0] --- */
        double S  = p00 + R;                        /* дисперсия невязки */
        double K0 = p00 / S;                        /* усиление по положению */
        double K1 = p10 / S;                        /* усиление по скорости (через связь!) */
        double innovation = z - x;

        x += K0 * innovation;
        v += K1 * innovation;

        /* P = (I - K H) P */
        double u00 = (1.0 - K0) * p00;
        double u01 = (1.0 - K0) * p01;
        double u10 = p10 - K1 * p00;
        double u11 = p11 - K1 * p01;
        p00 = u00; p01 = u01; p10 = u10; p11 = u11;

        double meas_err = z - true_x; if (meas_err < 0) meas_err = -meas_err;
        double est_err  = x - true_x; if (est_err  < 0) est_err  = -est_err;
        sum_meas_err += meas_err;
        sum_est_err  += est_err;

        if (k <= 8 || k % 6 == 0)
            printf("%3d %8.1f %9.1f %9.1f %9.2f %8.3f %9.2f %10.2f\n",
                   k, true_x, z, x, v, K0, meas_err, est_err);
    }

    printf("\nсредняя ошибка измерения: %.2f м\n", sum_meas_err / STEPS);
    printf("средняя ошибка оценки:    %.2f м\n", sum_est_err / STEPS);
    printf("фильтр точнее сырого радара в %.1f раза\n", sum_meas_err / sum_est_err);
    printf("оценённая скорость: %.2f м/с (истинная %.0f)\n\n", v, true_v);

    printf("K0 падает от почти 1 до малых значений: чем увереннее фильтр,\n");
    printf("тем меньше он доверяет очередному измерению.\n");
    return 0;
}
