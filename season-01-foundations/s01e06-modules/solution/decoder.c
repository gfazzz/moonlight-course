/*
 * OPERATION MOONLIGHT — s01e06 "Модули и сборка"
 * Главная программа: использует модуль crypto через #include "crypto.h".
 *
 * Больше никакого копипаста XOR: декодирование живёт в одном месте (crypto.c),
 * а main лишь оркеструет. Это и есть модульность.
 */
#include <stdio.h>
#include "crypto.h"

#define XOR_KEY 0x42

int main(void) {
    unsigned char msg[] = {
        0x0F, 0x0D, 0x0D, 0x0C, 0x0E, 0x0B, 0x05, 0x0A,
        0x16, 0x62, 0x23, 0x21, 0x36, 0x2B, 0x34, 0x23,
        0x36, 0x27, 0x26, 0x6C, 0x48, 0x16, 0x2A, 0x27,
        0x3B, 0x62, 0x29, 0x2C, 0x2D, 0x35, 0x6C, 0x48,
        0x04, 0x2B, 0x2E, 0x27, 0x31, 0x62, 0x23, 0x36,
        0x62, 0x2D, 0x2E, 0x26, 0x62, 0x32, 0x2E, 0x23,
        0x21, 0x27, 0x6C, 0x48, 0x16, 0x30, 0x37, 0x31,
        0x36, 0x62, 0x2D, 0x2C, 0x2E, 0x3B, 0x62, 0x21,
        0x2D, 0x26, 0x27, 0x6C, 0x48, 0xA0, 0xC2, 0xD6,
        0x62, 0x14, 0x6C
    };
    int len = (int)(sizeof(msg) / sizeof(msg[0]));

    printf("=== MOONLIGHT DECODER (modular) ===\n");
    printf("Module: crypto v1\n\n");

    xor_crypt(msg, len, XOR_KEY);      /* расшифровка через модуль */
    unsigned char sum = checksum(msg, len);

    for (int i = 0; i < len; i++) putchar(msg[i]);
    printf("\n\nChecksum: 0x%02X\n", sum);
    return 0;
}
